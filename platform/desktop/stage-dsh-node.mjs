import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { compilePackagedTypeScriptPlugin } from './packaged-typescript.mjs'
import { copyRuntimePackage } from './runtime-dependencies.mjs'

/** Stage the launcher using the same entry path as the shipped launchers. */
export function stageDshNode({ typescript, packageRoot, destination, dependencyRoot }) {
  copyRuntimePackage(packageRoot, destination)
  // Preserve the launcher's src/ depth for import.meta.url-based paths. The
  // same compiler follows and checks the complete runtime relative import
  // graph; cross-package source layout is never assumed inside the app.
  const emitted = compilePackagedTypeScriptPlugin({
    typescript, packageName: '@lumo/dsh-node', packageRoot, destination,
    dependencyRoot, outputDirectory: 'src',
  })
  // Both shipped launchers call this stable path with Node's strip-types.
  // Runtime code is already JS, including shared classes with parameter
  // properties that strip-types cannot transform.
  writeFileSync(resolve(destination, 'src/index.ts'), "// Compiled desktop entry; generated by stage-dsh-node.mjs.\nimport './index.js'\n")
  return emitted
}
